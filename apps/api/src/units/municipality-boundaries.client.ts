import { readFile } from 'node:fs/promises';
import { Injectable, type OnModuleInit } from '@nestjs/common';
import type { Polygon } from './geometry.js';

/** Municipality boundaries by 6-digit IBGE code, as CNES identifies them. */
export type MunicipalityBoundaries = Map<string, Polygon[]>;

type BoundariesByState = Record<string, Record<string, Polygon[]>>;

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value);
}

function parseBoundariesFile(content: string): BoundariesByState {
  const file: unknown = JSON.parse(content);
  if (
    !isRecord(file) ||
    !isRecord(file.boundaries) ||
    Object.keys(file.boundaries).length === 0 ||
    !Object.values(file.boundaries).every(isRecord)
  ) {
    throw new Error('Invalid municipality boundaries file');
  }
  return file.boundaries as BoundariesByState;
}

@Injectable()
export class MunicipalityBoundariesClient implements OnModuleInit {
  private boundaries: BoundariesByState = {};

  /**
   * Reads the simplified boundaries of every municipality from the bundled
   * file, generated by `scripts/generate-municipality-boundaries.mjs`. They are
   * not fetched at runtime because the IBGE host can be unreachable from the
   * server. A bad file stops the startup: otherwise every coordinate would be
   * served unchecked.
   */
  async onModuleInit(): Promise<void> {
    this.boundaries = parseBoundariesFile(
      await readFile(
        new URL('./municipality-boundaries.json', import.meta.url),
        'utf8',
      ),
    );
  }

  /** The boundaries of every municipality of one state. */
  async fetch(stateAbbreviation: string): Promise<MunicipalityBoundaries> {
    const municipalities = this.boundaries[stateAbbreviation];
    if (!municipalities) {
      throw new Error(`No boundaries for state ${stateAbbreviation}`);
    }
    return new Map(Object.entries(municipalities));
  }
}
